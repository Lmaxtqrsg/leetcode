// 2022 计算机挑战赛 C++ 操作题 46：二维数组周边元素之和
// 输入：第一行 n（2<=n<=100），接下来 n 行每行 n 个整数（元素之间两个空格）
// 输出：一个整数，最外一圈元素之和
// 状态：独立 AC（一遍过）
// 复杂度：O(n) —— 只走四条边，不扫全表
//
// 思路：四条边错位遍历，每条边少算一个角、由下一条边接走，总数 4(n-1) = 4n-4 = 周长格数
//   上行 a[0][0 .. n-2]       算到左上，让出右上
//   右列 a[0 .. n-2][n-1]     算到右上，让出右下
//   下行 a[n-1][n-1 .. 1]     算到右下，让出左下
//   左列 a[n-1 .. 1][0]       算到左下，让出左上
// 这样天然不重不漏，不需要任何 if 判断；同样套路可用于蛇形填数 / 螺旋矩阵

#include <iostream>
using namespace std;

int main() {
    int n;
    cin >> n;

    int a[105][105];
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < n; j++) {
            cin >> a[i][j];
        }
    }

    int sum = 0;

    for (int i = 0; i < n - 1; i++) sum += a[0][i];         // 上行，让出右上角
    for (int j = 0; j < n - 1; j++) sum += a[j][n - 1];     // 右列，让出右下角
    for (int k = n - 1; k > 0; k--) sum += a[n - 1][k];     // 下行，让出左下角
    for (int m = n - 1; m > 0; m--) sum += a[m][0];         // 左列，让出左上角

    cout << sum << "\n";
    return 0;
}

