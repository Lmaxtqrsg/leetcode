// 2021 计算机挑战赛 C++ 操作题 50：信息整理（位运算）
// 输入：第一行 N（0<N<=1000）；接下来 N 行，每行一个 0~15 的整数
// 输出：一个整数，键盘或鼠标故障的计算机台数
// 状态：看题解 AC（第一版走「转二进制 + 栈取位」，补零和空栈都出错）
// 复杂度：O(N)
//
// 题目映射（注意是「从左到右」）：
//   第 0 位 键盘 | 第 1 位 鼠标 | 第 2 位 显示 | 第 3 位 声音
//   对应二进制：bit3      | bit2      | bit1      | bit0
//   验证：7 = 0111 → 键盘 0、鼠标 1、显示 1、声音 1 → 「鼠标、显示、声音同时故障」✓
//
// 卡点归因：
//   ②建模  第一反应是「十进制转二进制再取每一位」，绕了整整一圈
//   ③语法  stack 空栈 top() 是未定义行为（输入 0 时直接崩）
//   ③语法  转二进制没补前导零（4=100 只有 3 位，位全部错位）
//   ②建模  每台单独算 count，没有跨台累加，也没有输出
//
// 正解：这题考的是位提取，不是进制转换
//   取第 k 位：(x >> k) & 1
//   判断某几位是否有 1：x & 掩码，非 0 即命中
//   键盘或鼠标 = bit3 或 bit2 = x & 0b1100 = x & 12

#include <iostream>
using namespace std;

int main() {
    int N;
    cin >> N;

    int total = 0;                  // 累加器必须放在循环外面
    while (N--) {
        int a;
        cin >> a;
        if (a & 12) total++;        // 12 = 1100，高两位（键盘/鼠标）有一位是 1 就算
    }

    cout << total << "\n";
    return 0;
}
